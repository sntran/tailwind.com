// Makes native/tailwind/src/compat/default_theme.rs from compat/default-theme.ts of the upstream clone.
// Usage: node gen-default-theme.mjs /path/to/tw OUTPUT.rs
//
// The theme has functions of two forms: "theme('key')" and an object literal with
// "...theme('key')" parts. The script calls each function with a theme function that
// returns a marked object, and thus finds the form and the keys.
import fs from 'node:fs'
import { createRequire } from 'node:module'
import path from 'node:path'

let [clone, output] = process.argv.slice(2)
clone = path.resolve(clone)
let nodePackage = path.join(clone, 'packages/@tailwindcss-node')
let require = createRequire(path.join(nodePackage, 'package.json'))
let { createJiti } = require('jiti')
let jiti = createJiti(path.join(clone, 'packages/tailwindcss/src/'), { moduleCache: true })
let defaultTheme = (await jiti.import(path.join(clone, 'packages/tailwindcss/src/compat/default-theme.ts'))).default

const MARK = '\u0000spread:'

function str(text) {
  return JSON.stringify(text).replace(/\$/g, '\\u{24}')
}

function isIndex(key) {
  return /^(0|[1-9][0-9]*)$/.test(key)
}

function literal(value, depth) {
  let pad = '    '.repeat(depth)
  if (value === null) return 'Val::Null'
  if (typeof value === 'string') return `s(${str(value)})`
  if (typeof value === 'function') return 'Val::Opaque'
  if (Array.isArray(value)) {
    return `a(vec![${value.map((v) => literal(v, depth)).join(', ')}])`
  }
  if (typeof value === 'object') {
    let lines = Object.keys(value).map((key) => `${pad}    (${str(key)}, ${literal(value[key], depth + 1)}),`)
    return `o(vec![\n${lines.join('\n')}\n${pad}])`
  }
  throw new Error(`Unexpected value: ${typeof value}`)
}

function lazy(name, fn) {
  let sentinels = new Map()
  let theme = (key, ...rest) => {
    if (rest.length > 0) throw new Error(`${name}: theme() with a default value`)
    if (!sentinels.has(key)) sentinels.set(key, { [MARK + key]: true })
    return sentinels.get(key)
  }
  let result = fn({ theme })
  for (let [key, sentinel] of sentinels) {
    if (result === sentinel) return `Val::Lazy(Rc::new(Lazy::Theme(${str(key)})))`
  }
  let keys = Object.keys(result)
  let hasSpread = keys.some((key) => key.startsWith(MARK))
  // JavaScript puts the index keys first. Then the position of a spread is not known.
  if (hasSpread && keys.some(isIndex)) throw new Error(`${name}: index keys and a spread`)
  let parts = keys.map((key) => {
    if (key.startsWith(MARK)) return `        Part::Spread(${str(key.slice(MARK.length))}),`
    return `        Part::Entry(${str(key)}, ${literal(result[key], 2)}),`
  })
  return `Val::Lazy(Rc::new(Lazy::Object(vec![\n${parts.join('\n')}\n    ])))`
}

let entries = []
for (let [name, value] of Object.entries(defaultTheme)) {
  // The compatibility configuration always replaces `colors`.
  if (name === 'colors') {
    entries.push(`    (${str(name)}, Val::Lazy(Rc::new(Lazy::ThemeOrEmpty("color")))),`)
  } else if (typeof value === 'function') {
    entries.push(`    (${str(name)}, ${lazy(name, value)}),`)
  } else {
    entries.push(`    (${str(name)}, ${literal(value, 1)}),`)
  }
}

let text = `//! The default theme of the compatibility layer: \`compat/default-theme.ts\`
//! of Tailwind CSS.
//!
//! GENERATED by \`tests/upstream/tools/gen-default-theme.mjs\`. Do not edit.
//! The key \`colors\` has the function of \`compat/config/create-compat-config.ts\`.

use super::theme_fn::{a, o, s, Lazy, Part, Val};
use std::rc::Rc;

/// The keys and values of the default theme, in the sequence of upstream.
#[rustfmt::skip]
pub(super) fn default_theme() -> Vec<(&'static str, Val)> {
    vec![
${entries.join('\n')}
    ]
}
`
fs.writeFileSync(output, text)
console.log(`${entries.length} keys`)
