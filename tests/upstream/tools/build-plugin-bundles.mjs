#!/usr/bin/env node
// Usage: node build-plugin-bundles.mjs <upstream clone> [output directory]
//
// This script makes the other JavaScript files of the program, with esbuild:
//
// - native/tailwind/assets/plugins/NAME.js: the plugins that the standalone
//   program of Tailwind CSS has in its file (packages/@tailwindcss-standalone:
//   @tailwindcss/forms, @tailwindcss/typography, @tailwindcss/aspect-ratio),
//   each one with its dependencies as one CommonJS file. The modules
//   `tailwindcss/...` stay as `require` calls: the program has them.
// - native/tailwind/assets/typescript.js: the TypeScript transform of
//   Sucrase, for TypeScript configs and plugins (native/tailwind/js/typescript-entry.ts).
//
// The packages come from tests/upstream/tools/node_modules (run "npm install"
// in tests/upstream/tools). The versions of the plugins in package.json must
// be the versions of the lock file of Tailwind CSS: the script stops when
// they are not.
import fs from 'node:fs'
import { createRequire } from 'node:module'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

let [upstream, output] = process.argv.slice(2)
if (!upstream) {
  console.error('Usage: node build-plugin-bundles.mjs <upstream clone> [output directory]')
  process.exit(2)
}
upstream = path.resolve(upstream)

let here = path.dirname(fileURLToPath(import.meta.url))
let root = path.resolve(here, '../../..')
output = path.resolve(output ?? path.join(root, 'native/tailwind/assets'))
let require = createRequire(path.join(here, 'package.json'))

let esbuild
try {
  esbuild = require('esbuild')
} catch {
  console.error('build-plugin-bundles.mjs: esbuild is not there. Run "npm install" in tests/upstream/tools.')
  process.exit(1)
}

// The plugins of the standalone program, and their versions in its lock file.
let standalone = JSON.parse(
  fs.readFileSync(path.join(upstream, 'packages/@tailwindcss-standalone/package.json'), 'utf8'),
)
let plugins = Object.keys(standalone.dependencies).filter(
  (name) => name.startsWith('@tailwindcss/') && standalone.dependencies[name] !== 'workspace:*',
)
let source = fs.readFileSync(path.join(upstream, 'packages/@tailwindcss-standalone/src/index.ts'), 'utf8')
let lock = fs.readFileSync(path.join(upstream, 'pnpm-lock.yaml'), 'utf8')

let failed = false
let versions = {}
for (let name of plugins) {
  if (!source.includes(`require('${name}')`)) {
    console.error(`build-plugin-bundles.mjs: ${name} is a dependency of the standalone program, but its index.ts does not load it.`)
    failed = true
  }
  let match = lock.match(new RegExp(`^  '${name.replace('/', '\\/')}@([0-9][^'(]*)':$`, 'm'))
  let wanted = match?.[1]
  let installed
  try {
    installed = JSON.parse(fs.readFileSync(path.join(here, 'node_modules', name, 'package.json'), 'utf8')).version
  } catch {
    console.error(`build-plugin-bundles.mjs: ${name} is not there. Run "npm install" in tests/upstream/tools.`)
    process.exit(1)
  }
  if (wanted !== installed) {
    console.error(
      `build-plugin-bundles.mjs: ${name} is ${installed} here, and ${wanted} in the lock file of Tailwind CSS. Change tests/upstream/tools/package.json and run "npm install".`,
    )
    failed = true
  }
  versions[name] = installed
}
// A plugin that index.ts loads and this script does not know.
for (let match of source.matchAll(/require\('(@tailwindcss\/[^']+)'\)/g)) {
  if (!plugins.includes(match[1])) {
    console.error(`build-plugin-bundles.mjs: the standalone program loads ${match[1]}: add it to tests/upstream/tools/package.json.`)
    failed = true
  }
}
if (failed) process.exit(1)

fs.mkdirSync(path.join(output, 'plugins'), { recursive: true })

function packagesOf(metafile) {
  let names = new Set()
  for (let [file, info] of Object.entries(Object.values(metafile.outputs)[0].inputs)) {
    if (info.bytesInOutput === 0) continue
    let match = file.match(/node_modules\/((?:@[^/]+\/)?[^/]+)\//g)
    if (!match) continue
    let name = match[match.length - 1].slice('node_modules/'.length, -1)
    let version = JSON.parse(fs.readFileSync(path.join(here, 'node_modules', name, 'package.json'), 'utf8')).version
    names.add(`${name} ${version}`)
  }
  return [...names].sort()
}

for (let name of plugins) {
  let result = await esbuild.build({
    entryPoints: [require.resolve(name)],
    bundle: true,
    format: 'cjs',
    platform: 'node',
    target: 'es2022',
    minify: true,
    legalComments: 'none',
    write: false,
    metafile: true,
    external: ['tailwindcss', 'tailwindcss/*'],
  })
  let packages = packagesOf(result.metafile)
  let header = `// Generated by tests/upstream/tools/build-plugin-bundles.mjs. Do not edit.
// ${name} ${versions[name]} with its dependencies (${packages.filter((item) => !item.startsWith(name + ' ')).join(', ') || 'none'}).
// The licenses are in NOTICE and licenses/ of tailwind.com.
`
  let file = path.join(output, 'plugins', name.replace('@tailwindcss/', '') + '.js')
  fs.writeFileSync(file, header + result.outputFiles[0].text)
  console.error(`build-plugin-bundles.mjs: wrote ${file} (${fs.statSync(file).size} bytes): ${packages.join(', ')}`)
}

// The TypeScript transform.
{
  let result = await esbuild.build({
    entryPoints: [path.join(root, 'native/tailwind/js/typescript-entry.ts')],
    bundle: true,
    format: 'iife',
    globalName: '__tw_typescript',
    platform: 'neutral',
    mainFields: ['module', 'main'],
    target: 'es2022',
    minify: true,
    legalComments: 'none',
    write: false,
    metafile: true,
    nodePaths: [path.join(here, 'node_modules')],
    // The value of the script is the function.
    footer: { js: '__tw_typescript.default' },
  })
  let packages = packagesOf(result.metafile)
  let header = `// Generated by tests/upstream/tools/build-plugin-bundles.mjs. Do not edit.
// The TypeScript transform of ${packages.join(', ')} (MIT License), with native/tailwind/js/typescript-entry.ts.
`
  let file = path.join(output, 'typescript.js')
  fs.writeFileSync(file, header + result.outputFiles[0].text)
  console.error(`build-plugin-bundles.mjs: wrote ${file} (${fs.statSync(file).size} bytes): ${packages.join(', ')}`)
}
